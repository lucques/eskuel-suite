-- Create the "driving_instructor" table
CREATE TABLE IF NOT EXISTS driving_instructor (
    code TEXT PRIMARY KEY,
    first_name TEXT,
    last_name TEXT,
    phone_number TEXT
);

-- Create the "driving_student" table
CREATE TABLE IF NOT EXISTS driving_student (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    first_name TEXT,
    last_name TEXT,
    date_of_birth DATE,
    theory_test_passed BOOLEAN,
    number_of_driving_lessons INTEGER,
    instructor_code TEXT,
    FOREIGN KEY (instructor_code) REFERENCES driving_instructor(code)
);

